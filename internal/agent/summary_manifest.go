const (
	// manifestTokenBudget caps the size of the machine-generated manifest.
	// The manifest is the authoritative fact sheet, but it is still context
	// the model reads: an unbounded index would recreate the problem the
	// summary exists to solve.
	manifestTokenBudget = 1500
	// manifestMaxFailures bounds the section that can grow with session
	// length. It is ordered newest first, so the cut keeps the most
	// relevant entries. Files have no structural cap: the budget loop is
	// the only thing that trims them, so a session that touched thirty
	// files still names all thirty while the block fits.
	manifestMaxFailures = 10
	// manifestWriteLedgerLimit bounds the ledger query, not the manifest:
	// the budget renders far fewer paths than this, so the limit only stops
	// a long session from reading thousands of rows to discard them.
	manifestWriteLedgerLimit = 200
)

// manifestLeadIn introduces the block. The appendix marker already says the
// text is data rather than instructions; what this line adds is provenance,
// because the manifest quotes the user's own commands and tool output, and a
// quoted command must not read as a new request.
const manifestLeadIn = "Machine-generated from the archived transcript; not written by the user.\n\n"

// manifestFailureMarkers are the lines that most often identify why a
// command failed. The first match becomes the failure's `key` so the model
// can judge relevance without opening the payload.
var manifestFailureMarkers = []string{
	"--- FAIL",
	"FAIL",
	"panic:",
	"Traceback",
	"error[E",
	"Error:",
}

// manifestInput is everything buildContextManifest needs. It is a plain
// value so the manifest stays pure: no session service, no clock, no I/O.
type manifestInput struct {
	// Messages are the messages strictly before the summary anchor being
	// replaced.
	Messages []message.Message
	// AnchorAt is the timestamp the archive ends at, and the range start
	// when Messages is empty.
	AnchorAt int64
	// GeneratedAt stamps the block. Zero falls back to AnchorAt so a test
	// that does not care about the stamp still gets a valid value.
	GeneratedAt time.Time
	// Undecodable counts archived messages that could not be decoded and
	// are therefore absent from Messages. It lets the manifest say "not
	// indexed" instead of silently implying "did not happen".
	Undecodable int
	// Worktree lists paths git reports as changed, which covers edits made
	// through a shell command rather than a file tool. Nil means git was
	// not consulted or failed; the renderer then says so instead of
	// implying the tree is clean.
	Worktree []manifestWorktreeFile
	// WorktreeKnown is true when Worktree is an authoritative answer,
	// including the legitimately empty one for a clean tree.
	WorktreeKnown bool
	// Files are the files the session's write ledger recorded, already
	// shortened against the workspace. They cover edits made through a
	// file tool; git covers everything else and is the authority when the
	// two disagree.
	Files []manifestFile
}

type manifestFailure struct {
	ToolCallID string
	Tool       string
	Exit       int
	HasExit    bool
	Command    string
	Key        string
	At         int64
}

type manifestFile struct {
	Path string
	Last int64
	// Worktree marks a path that git reports as changed. Such a path may
	// carry no ledger entry if the change came from a shell command.
	Worktree bool
	// Status is git's word for the change, empty for ledger-only paths.
	Status string
}

// buildContextManifest renders the `<context_manifest>` block appended to a
// summary. It is generated by code from the archived messages, never by the
// model: published evaluations put artifact tracking at the bottom of every
// summarizer's accuracy table, so paths and exit codes are facts the harness
// must guarantee rather than ask for.
//
// Returns "" when there is nothing to report.
func buildContextManifest(in manifestInput) string {
	if len(in.Messages) == 0 && in.Undecodable == 0 {
		return ""
	}

	generated := in.GeneratedAt
	if generated.IsZero() {
		generated = time.Unix(in.AnchorAt, 0)
	}

	var (
		failures, failuresDropped = manifestFailures(in.Messages)
		files                     = manifestFiles(in.Files, in.Worktree)
		bashCalls                 = countBashCalls(in.Messages)
	)

	// The model reads this block, so its budget is enforced by shrinking
	// the sections that can grow — files first (the per-file `why` lives
	// in `## Artifacts` prose), then failures. Files carry no structural
	// cap, so this loop is the only thing that trims them.
	//
	// Truncation is expressed as a trailing count line rather than by
	// silently dropping entries, so the reader can tell a short list from
	// a clipped one.
	filesDropped := 0
	for {
		block := renderManifest(manifestRenderInput{
			generatedAt:     generated,
			messages:        in.Messages,
			anchorAt:        in.AnchorAt,
			undecodable:     in.Undecodable,
			failures:        failures,
			files:           files,
			filesDropped:    filesDropped,
			failuresDropped: failuresDropped,
			worktreeKnown:   in.WorktreeKnown,
			bashCalls:       bashCalls,
		})
		if approxTokenCount(block) <= manifestTokenBudget {
			return block
		}
		switch {
		case len(files) > 0:
			files = files[:len(files)-1]
			filesDropped++
		case len(failures) > 0:
			failures = failures[:len(failures)-1]
			failuresDropped++
		default:
			// Nothing left to drop; return what we have rather than loop.
			return block
		}
	}
}

type manifestRenderInput struct {
	generatedAt     time.Time
	messages        []message.Message
	anchorAt        int64
	undecodable     int
	failures        []manifestFailure
	files           []manifestFile
	filesDropped    int
	failuresDropped int
	worktreeKnown   bool
	bashCalls       int
}

func renderManifest(in manifestRenderInput) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "<context_manifest generated=%q>\n", in.generatedAt.UTC().Format(time.RFC3339))

	// The archived line is the headline: how much was replaced, when, and
	// how much of it failed.
	toolCalls := 0
	for _, m := range in.messages {
		toolCalls += len(m.ToolCalls())
	}
	first, last := archiveRange(in.messages, in.anchorAt)
	fmt.Fprintf(
		&sb,
		"archived: messages=%d range=%s..%s tool_calls=%d tool_result_bytes=%d failures=%d\n",
		len(in.messages),
		formatManifestTime(first),
		formatManifestTime(last),
		toolCalls,
		archivedToolResultBytes(in.messages),
		len(in.failures)+in.failuresDropped,
	)

	if len(in.failures) > 0 || in.failuresDropped > 0 {
		sb.WriteString("failures:\n")
		for _, f := range in.failures {
			fmt.Fprintf(&sb, "- tool=%s", manifestEscape(f.Tool))
			if f.HasExit {
				fmt.Fprintf(&sb, " exit=%d", f.Exit)
			}
			if f.Command != "" {
				fmt.Fprintf(&sb, " cmd=%q", manifestEscape(f.Command))
			}
			if f.Key != "" {
				fmt.Fprintf(&sb, " key=%q", manifestEscape(f.Key))
			}
			// `tool_call_id` is the handle `recall` takes. It comes
			// last so the fields §4.4 fixes keep their order.
			if f.ToolCallID != "" {
				fmt.Fprintf(&sb, " tool_call_id=%s", manifestEscape(f.ToolCallID))
			}
			sb.WriteString("\n")
		}
		if in.failuresDropped > 0 {
			fmt.Fprintf(&sb, "- (truncated: %d more)\n", in.failuresDropped)
		}
	}

	if len(in.files) > 0 || in.filesDropped > 0 || !in.worktreeKnown || in.bashCalls > 0 {
		sb.WriteString("files:\n")
		for _, f := range in.files {
			fmt.Fprintf(&sb, "- path=%s", manifestEscape(f.Path))
			if f.Last > 0 {
				fmt.Fprintf(&sb, " last=%s", formatManifestTime(f.Last))
			}
			if f.Worktree {
				fmt.Fprintf(&sb, " src=git state=%s", f.Status)
			} else {
				sb.WriteString(" src=tool")
			}
			sb.WriteString("\n")
		}
		if in.filesDropped > 0 {
			fmt.Fprintf(&sb, "- (truncated: %d more)\n", in.filesDropped)
		}
		// The list is only authoritative when git answered. Saying so
		// keeps "no file changed" distinguishable from "no file tool ran
		// and nothing verified the tree", which is the common case for an
		// agent that edits through shell commands.
		if !in.worktreeKnown {
			fmt.Fprintf(
				&sb,
				"- (working tree not checked; %d bash call(s) may have modified files)\n",
				in.bashCalls,
			)
		} else if len(in.files) == 0 && in.bashCalls > 0 {
			fmt.Fprintf(
				&sb,
				"- (working tree clean; %d bash call(s) reported no changes)\n",
				in.bashCalls,
			)
		}
	}

	// Coverage distinguishes "not there" from "not indexed".
	fmt.Fprintf(&sb, "coverage: %d/%d archived messages scanned", len(in.messages), len(in.messages)+in.undecodable)
	if in.undecodable > 0 {
		fmt.Fprintf(&sb, " (%d undecodable)", in.undecodable)
	}
	sb.WriteString("\n</context_manifest>")
	return sb.String()
}

// archivedToolResultBytes totals the archived tool output. The model has no
// other way to tell a session whose tool calls carried four kilobytes from one
// that carried four hundred, which is the cost signal §4.3 wants the
// tombstone's byte count for.
func archivedToolResultBytes(msgs []message.Message) int {
	total := 0
	for _, m := range msgs {
		if m.Role != message.Tool {
			continue
		}
		for _, r := range m.ToolResults() {
			total += len(r.Content) + len(r.Data)
		}
	}
	return total
}

func archiveRange(msgs []message.Message, anchorAt int64) (int64, int64) {
	if len(msgs) == 0 {
		return anchorAt, anchorAt
	}
	first, last := msgs[0].CreatedAt, msgs[0].CreatedAt
	for _, m := range msgs[1:] {
		if m.CreatedAt < first {
			first = m.CreatedAt
		}
		if m.CreatedAt > last {
			last = m.CreatedAt
		}
	}
	return first, last
}

func formatManifestTime(unix int64) string {
	return time.Unix(unix, 0).UTC().Format(time.RFC3339)
}

// manifestToolCall is one archived tool call, joined to its result when the
// archive contains one, so a result can be attributed to the call's name,
// command and timestamp.
type manifestToolCall struct {
	Name   string
	Input  string
	At     int64
	Result *message.ToolResult
}

func indexManifestToolCalls(msgs []message.Message) map[string]*manifestToolCall {
	calls := make(map[string]*manifestToolCall)
	for _, m := range msgs {
		for _, tc := range m.ToolCalls() {
			calls[tc.ID] = &manifestToolCall{
				Name:  tc.Name,
				Input: tc.Input,
				At:    m.CreatedAt,
			}
		}
	}
	for _, m := range msgs {
		for _, r := range m.ToolResults() {
			if call, ok := calls[r.ToolCallID]; ok {
				result := r
				call.Result = &result
			}
		}
	}
	return calls
}

// manifestFailures lists archived failures, newest first, and how many were
// cut by the structural cap. A failure is a tool result flagged `IsError`, or
// a bash result whose own status line reports a non-zero exit (the
// model-facing result does not always carry IsError).
func manifestFailures(msgs []message.Message) ([]manifestFailure, int) {
	calls := indexManifestToolCalls(msgs)

	var failures []manifestFailure
	for _, call := range calls {
		if call.Result == nil {
			continue
		}
		f := manifestFailure{
			ToolCallID: call.Result.ToolCallID,
			Tool:       manifestToolName(call),
			Command:    manifestCommand(call),
			At:         call.At,
		}
		if tools.IsBashToolName(f.Tool) {
			if code, ok := tools.ParseExitCode(call.Result.Content); ok {
				f.Exit = code
				f.HasExit = true
			}
		}
		if !call.Result.IsError && !(f.HasExit && f.Exit != 0) {
			continue
		}
		f.Key = manifestFailureKey(call.Result.Content)
		failures = append(failures, f)
	}

	slices.SortFunc(failures, func(a, b manifestFailure) int {
		// Results batched into one assistant message share the timestamp
		// and arrive in map order, so the tool call id is what keeps the
		// order stable across runs.
		return newestFirst(a.At, b.At, a.ToolCallID, b.ToolCallID)
	})
	return capManifest(failures, manifestMaxFailures)
}

func manifestToolName(call *manifestToolCall) string {
	if call.Name != "" {
		return call.Name
	}
	if call.Result != nil {
		return call.Result.Name
	}
	return "unknown"
}

// manifestFailureKey picks the line that best explains the failure: the first
// line carrying a known failure marker, or the first non-empty line.
func manifestFailureKey(content string) string {
	var firstNonEmpty string
	for _, line := range strings.Split(content, "\n") {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		if firstNonEmpty == "" {
			firstNonEmpty = trimmed
		}
		if hasFailureMarker(trimmed) {
			return clipManifestLine(trimmed)
		}
	}
	return clipManifestLine(firstNonEmpty)
}

const manifestLineLimit = 200

func clipManifestLine(s string) string {
	if len(s) <= manifestLineLimit {
		return s
	}
	runes := []rune(s)
	if len(runes) <= manifestLineLimit {
		return s
	}
	return string(runes[:manifestLineLimit]) + "…"
}

// manifestFiles merges the session's write ledger with the paths git reports
// as changed, most recent first. The ledger is what this session wrote; git
// adds edits made through a shell command, which no tool input can name
// reliably. A path in both sets appears once, marked src=git because git is
// the authority on the resulting state.
func manifestFiles(writes []manifestFile, worktree []manifestWorktreeFile) []manifestFile {
	byPath := make(map[string]*manifestFile, len(writes)+len(worktree))
	var order []string
	for _, w := range writes {
		if w.Path == "" {
			continue
		}
		if existing, seen := byPath[w.Path]; seen {
			if w.Last > existing.Last {
				existing.Last = w.Last
			}
			continue
		}
		entry := w
		byPath[w.Path] = &entry
		order = append(order, w.Path)
	}

	// A path git reports as changed is authoritative that it changed, even
	// when the ledger has no entry: the edit may have gone through a shell
	// command, whose arguments name no path we can trust. Merge by path so a
	// file that was both written by a tool and is dirty appears once.
	for _, wf := range worktree {
		if wf.Path == "" {
			continue
		}
		f, seen := byPath[wf.Path]
		if !seen {
			f = &manifestFile{Path: wf.Path}
			byPath[wf.Path] = f
			order = append(order, wf.Path)
		}
		f.Worktree = true
		f.Status = wf.Status
	}

	files := make([]manifestFile, 0, len(order))
	for _, path := range order {
		files = append(files, *byPath[path])
	}
	slices.SortFunc(files, func(a, b manifestFile) int {
		return newestFirst(a.Last, b.Last, a.Path, b.Path)
	})
	return files
}

// manifestCommand extracts the shell command from a bash tool call.
func manifestCommand(call *manifestToolCall) string {
	if !tools.IsBashToolName(manifestToolName(call)) {
		return ""
	}
	var params struct {
		Command string `json:"command"`
	}
	if err := json.Unmarshal([]byte(call.Input), &params); err != nil {
		return ""
	}
	return params.Command
}

// newestFirst orders two archive timestamps newest-first, falling back to a
// string key when the timestamps tie. Timestamps have one-second resolution,
// so ties are common and an unstable order would make the manifest differ
// between two runs over the same session.
func newestFirst(atA, atB int64, keyA, keyB string) int {
	if atA != atB {
		return cmp.Compare(atB, atA)
	}
	return strings.Compare(keyA, keyB)
}

// capManifest truncates entries to max and reports how many were dropped, so
// the renderer can say so instead of silently shrinking the section.
func capManifest[T any](entries []T, max int) ([]T, int) {
	if len(entries) <= max {
		return entries, 0
	}
	return entries[:max], len(entries) - max
}

// manifestEscape escapes an interpolated value for the XML fence. Newlines
// are flattened because every section is line-oriented: a value with a line
// break would corrupt the entry that follows.
func manifestEscape(s string) string {
	r := strings.NewReplacer(
		"&", "&amp;",
		"<", "&lt;",
		">", "&gt;",
		"\r\n", " ",
		"\r", " ",
		"\n", " ",
	)
	return r.Replace(s)
}

// countBashCalls counts archived bash tool calls. Their file effects are
// invisible to the tool-call file index, so the files section reports the
// count when it has nothing else to say about them.
func countBashCalls(msgs []message.Message) int {
	calls := 0
	for _, m := range msgs {
		for _, tc := range m.ToolCalls() {
			if tools.IsBashToolName(tc.Name) {
				calls++
			}
		}
	}
	return calls
}
